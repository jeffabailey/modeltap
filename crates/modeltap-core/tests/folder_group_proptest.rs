proptest! {
    #![proptest_config(ProptestConfig {
        cases: 256,
        .. ProptestConfig::default()
    })]

    /// **AC-13 / M3 @property**: every model the classifier puts in `shared`
    /// MUST be a model that `compute_indicator` calls `Shared`, and every
    /// model in `unique` MUST be one of `{Compatible, FormatLocked, Unknown}`.
    /// Additionally, for every shared model the `other_tools` set MUST equal
    /// the distinct tools whose inventory entries share a dedup-key with the
    /// target (the peer-listing rule must align with the Shared-decision rule,
    /// preserving the single-engine invariant D-FGD-4).
    #[test]
    fn classification_matches_compute_indicator_for_every_child(
        folder in arb_folder_group(),
        peers in prop::collection::vec(arb_peer_entry(), 0..6),
        cap in arb_caps(),
    ) {
        // Build the full inventory: every folder model plus the random peers.
        let mut entries: Vec<InventoryEntry> =
            folder.models.iter().map(project_model).collect();
        entries.extend(peers);
        let inv = Inventory { entries };

        let classification = classify_unique_vs_shared(&folder, &inv, &cap);

        // Every shared bucket entry must independently classify as Shared,
        // and its `other_tools` must match the engine's peer set.
        for shared in &classification.shared {
            let target = project_model(&shared.model);
            let indicator = compute_indicator(&target, &inv, &cap);
            prop_assert_eq!(
                indicator,
                RowIndicator::Shared,
                "shared-bucket model must compute_indicator → Shared (single-engine D-FGD-4)"
            );

            // Independent recomputation of the peer set, mirroring
            // `peer_tools_sharing` in production: any peer in a DIFFERENT tool
            // with matching `Some(hash)` content.
            let expected_peers: Vec<ToolId> = inv
                .entries
                .iter()
                .filter(|e| e.tool != target.tool)
                .filter(|e| match (target.content_hash, e.content_hash) {
                    (Some(a), Some(b)) => a == b,
                    _ => false,
                })
                .fold(Vec::<ToolId>::new(), |mut acc, e| {
                    if !acc.contains(&e.tool) {
                        acc.push(e.tool);
                    }
                    acc
                });

            prop_assert_eq!(
                &shared.other_tools, &expected_peers,
                "other_tools must match the dedup-peer set (peer-listing == Shared-decision)"
            );
            prop_assert!(
                !shared.other_tools.is_empty(),
                "a Shared classification implies at least one other tool"
            );
        }

        // Every unique bucket entry must independently classify as one of
        // Compatible / FormatLocked / Unknown — NEVER Shared.
        for model in &classification.unique {
            let target = project_model(model);
            let indicator = compute_indicator(&target, &inv, &cap);
            prop_assert!(
                matches!(
                    indicator,
                    RowIndicator::Compatible
                        | RowIndicator::FormatLocked
                        | RowIndicator::Unknown
                ),
                "unique-bucket model must compute_indicator ∈ {{Compatible, FormatLocked, Unknown}}, got {:?}",
                indicator
            );
        }

        // Partition completeness: every folder model lands in exactly one bucket.
        prop_assert_eq!(
            classification.unique.len() + classification.shared.len(),
            folder.models.len(),
            "classification must partition folder.models (no drops, no duplicates)"
        );
    }
}

proptest! {
    #![proptest_config(ProptestConfig {
        cases: 256,
        .. ProptestConfig::default()
    })]

    /// **INT-FGD-2 @property**: `folder.file_count() == models.len() + sidecars.len()`.
    ///
    /// Trivial by construction, but pinned as a proptest so anyone who later
    /// refactors `FolderGroup::file_count` to (say) cache a precomputed value
    /// or to apply a "skip hidden sidecars" filter trips this gate before the
    /// reclaim-math seam silently drifts.
    #[test]
    fn file_count_equals_models_plus_sidecars(folder in arb_folder_group()) {
        prop_assert_eq!(
            folder.file_count(),
            folder.models.len() + folder.sidecars.len()
        );
    }
}

proptest! {
    #![proptest_config(ProptestConfig {
        cases: 256,
        .. ProptestConfig::default()
    })]

    /// **INT-FGD-3 @property**: `bytes_to_reclaim + bytes_to_retain == folder.total_bytes()`
    /// within 1-byte rounding tolerance.
    ///
    /// Construct the full plan via the production `build_folder_delete_plan`
    /// over a random `(folder, inventory, capabilities)` draw. The plan's
    /// smart constructor enforces the tolerance, so a violation would have
    /// panicked at construction; we additionally assert here to surface the
    /// concrete arithmetic relation in the failure output for a human
    /// reviewer.
    #[test]
    fn reclaim_plus_retain_equals_total_bytes_within_one_byte(
        folder in arb_folder_group(),
        peers in prop::collection::vec(arb_peer_entry(), 0..6),
        cap in arb_caps(),
    ) {
        let mut entries: Vec<InventoryEntry> =
            folder.models.iter().map(project_model).collect();
        entries.extend(peers);
        let inv = Inventory { entries };

        let classification = classify_unique_vs_shared(&folder, &inv, &cap);
        let plan = build_folder_delete_plan(&folder, &classification);

        let total = folder.total_bytes();
        let sum = plan.bytes_to_reclaim.saturating_add(plan.bytes_to_retain);
        prop_assert!(
            sum.abs_diff(total) <= 1,
            "reclaim ({}) + retain ({}) = {} must equal total ({}) within 1-byte tolerance",
            plan.bytes_to_reclaim,
            plan.bytes_to_retain,
            sum,
            total
        );

        // Path-count invariant (data-models §4): full-unlink paths + HF-only
        // paths == models.len() + sidecars.len(). Co-pinned here so a future
        // refactor cannot drift the byte math and the path math independently.
        prop_assert_eq!(
            plan.paths_to_unlink_fully.len() + plan.paths_to_unlink_hf_only.len(),
            folder.file_count(),
            "path counts must sum to folder.file_count()"
        );
    }
}

proptest! {
    #![proptest_config(ProptestConfig {
        cases: 256,
        .. ProptestConfig::default()
    })]

    /// **R1 / ADR-002 conservative-when-uncertain**: a model whose
    /// `dedup_key` is `Tentative` MUST NEVER appear in the `shared` bucket.
    ///
    /// `compute_indicator` refuses to call two entries shared when either
    /// side's SHA256 is `None`; `classify_unique_vs_shared` MUST inherit
    /// that property by routing through `compute_indicator`. This proptest
    /// pins the inheritance — if someone adds a shadow "label-equality
    /// fallback" inside the folder-group module that bypasses the engine,
    /// it would flip Tentative models into `shared` and this property would
    /// fail loudly.
    #[test]
    fn tentative_dedup_key_never_lands_in_shared_bucket(
        folder in arb_folder_group(),
        peers in prop::collection::vec(arb_peer_entry(), 0..6),
        cap in arb_caps(),
    ) {
        let mut entries: Vec<InventoryEntry> =
            folder.models.iter().map(project_model).collect();
        entries.extend(peers);
        let inv = Inventory { entries };

        let classification = classify_unique_vs_shared(&folder, &inv, &cap);

        for shared in &classification.shared {
            prop_assert!(
                matches!(shared.model.dedup_key, DedupKey::Content(_)),
                "Tentative dedup_key must NEVER be classified Shared (ADR-002 conservative); \
                 offending model id_in_tool={}",
                shared.model.id_in_tool
            );
        }
    }
}
