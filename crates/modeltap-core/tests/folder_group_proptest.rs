/// Project a folder's `ModelMeta` back into the `InventoryEntry` shape that
/// `compute_indicator` expects, mirroring the private helper in
/// `logic::folder_group::inventory_entry_for`. Kept separate from that helper
/// to avoid coupling the test to a private function — this is intentional
/// duplication of the projection, not the classification rule itself.
fn project_model(model: &ModelMeta) -> InventoryEntry {
    let content_hash = match &model.dedup_key {
        DedupKey::Content(hash) => Some(*hash),
        DedupKey::Tentative(_) => None,
    };
    InventoryEntry {
        tool: model.tool,
        model: DiscoveredModel {
            id_in_tool: model.id_in_tool.clone(),
            on_disk_path: model.on_disk_path.clone(),
            size_bytes: model.size_bytes,
            format: model.format,
            display_label: model.display_label.clone(),
            status: model.status.clone(),
        },
        content_hash,
    }
}

